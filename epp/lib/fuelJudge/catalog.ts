export function applicationsForStage(
  applications: FuelApplication[],
  stage: FuelStageConfig,
) {
  const statuses = new Set(stage.statuses);
  const pipelines = new Set(stage.pipelines);
  return applications.filter(
    (application) =>
      statuses.has(application.stage) && pipelines.has(application.pipeline),
  );
}
